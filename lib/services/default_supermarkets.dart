class DefaultSupermarketsData {
  static String _normalize(String text) {
    var result = text.toLowerCase().trim();
    const withDia = 'àáâãäåòóôõöøèéêëçìíîïùúûüñ';
    const noDia   = 'aaaaaaooooooeeeeciiiiuuuun';
    for (int i = 0; i < withDia.length; i++) {
      result = result.replaceAll(withDia[i], noDia[i]);
    }
    return result;
  }

  /// Encontra o supermercado com coordenadas mais próximo ou por correspondência de nome
  static PreloadedSupermarket? findMatch(String name, {double? userLat, double? userLng}) {
    final clean = name.trim();
    if (clean.isEmpty) return null;
    final cleanNorm = _normalize(clean);

    // 1. Busca exata (normalizada)
    for (final s in all) {
      if (_normalize(s.name) == cleanNorm) return s;
    }

    // 2. Busca onde contém ou tokens coincidem
    final tokens = cleanNorm.split(RegExp(r'[\s\-_/]+')).where((t) => t.isNotEmpty).toList();

    final candidates = all.where((s) {
      final sNorm = _normalize(s.name);
      if (sNorm.contains(cleanNorm) || cleanNorm.contains(sNorm)) return true;
      if (tokens.isNotEmpty && tokens.every((t) => sNorm.contains(t))) return true;
      return false;
    }).toList();

    if (candidates.length == 1) return candidates.first;

    if (candidates.isNotEmpty && userLat != null && userLng != null) {
      candidates.sort((a, b) {
        final distA = (a.latitude - userLat) * (a.latitude - userLat) + (a.longitude - userLng) * (a.longitude - userLng);
        final distB = (b.latitude - userLat) * (b.latitude - userLat) + (b.longitude - userLng) * (b.longitude - userLng);
        return distA.compareTo(distB);
      });
      return candidates.first;
    }

    return candidates.isNotEmpty ? candidates.first : null;
  }

